# 4. Classe GWO com Controle Fuzzy
class GWO_Fuzzy(GWO):
    def optimize(self):
        rng = np.random.default_rng(self.seed)
        positions = rng.uniform(self.lb, self.ub, size=(self.n_wolves, self.dim))
        fitness = np.array([self._eval(p) for p in positions])

        order = np.argsort(fitness)
        alpha_pos, alpha_score = positions[order[0]].copy(), fitness[order[0]]
        beta_pos, beta_score = positions[order[1]].copy(), fitness[order[1]]
        delta_pos, delta_score = positions[order[2]].copy(), fitness[order[2]]

        self.history = [alpha_score]
        self.hist_ajuste = []
        self.hist_a = []

        stagnation_count = 0

        for t in range(self.max_iter):
            # Diversidade normalizada entre 0 e 1
            diversidade = np.mean(np.std(positions, axis=0) / (self.ub - self.lb))
            diversidade = np.clip(diversidade, 0, 1)

            # Inferência Fuzzy com proteção
            simulador.input['diversidade'] = diversidade
            simulador.input['estagnacao'] = min(stagnation_count, 100)

            try:
                simulador.compute()
                fator_ajuste = simulador.output['ajuste']
            except KeyError:
                # Fallback: se nenhuma regra disparar, mantém o 'a' original (fator 1.0)
                fator_ajuste = 1.0

            a_base = self._compute_a(t)
            a = np.clip(a_base * fator_ajuste, 0, 2.0)

            self.hist_ajuste.append(fator_ajuste)
            self.hist_a.append(a)

            melhoria = False
            for i in range(self.n_wolves):
                for d in range(self.dim):
                    r1, r2 = rng.random(), rng.random()
                    A1 = 2 * a * r1 - a
                    C1 = 2 * r2
                    X1 = alpha_pos[d] - A1 * abs(C1 * alpha_pos[d] - positions[i, d])

                    r1, r2 = rng.random(), rng.random()
                    A2 = 2 * a * r1 - a
                    C2 = 2 * r2
                    X2 = beta_pos[d] - A2 * abs(C2 * beta_pos[d] - positions[i, d])

                    r1, r2 = rng.random(), rng.random()
                    A3 = 2 * a * r1 - a
                    C3 = 2 * r2
                    X3 = delta_pos[d] - A3 * abs(C3 * delta_pos[d] - positions[i, d])

                    positions[i, d] = (X1 + X2 + X3) / 3.0

                positions[i] = np.clip(positions[i], self.lb, self.ub)
                fit = self._eval(positions[i])

                if fit < alpha_score:
                    delta_pos, delta_score = beta_pos.copy(), beta_score
                    beta_pos, beta_score = alpha_pos.copy(), alpha_score
                    alpha_pos, alpha_score = positions[i].copy(), fit
                    melhoria = True
                elif fit < beta_score:
                    delta_pos, delta_score = beta_pos.copy(), beta_score
                    beta_pos, beta_score = positions[i].copy(), fit
                elif fit < delta_score:
                    delta_pos, delta_score = positions[i].copy(), fit

            if melhoria:
                stagnation_count = 0
            else:
                stagnation_count += 1

            self.history.append(alpha_score)

        return alpha_pos, alpha_score, np.array(self.history)

