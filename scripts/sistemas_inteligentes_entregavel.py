"""## 2. Implementação Canônica do GWO

Baseada em **Mirjalili, Mirjalili & Lewis (2014)** — *Grey Wolf Optimizer*, Advances in Engineering Software.

**Decisões de projeto:**
- Cada lobo é um vetor contínuo em `[lb, ub]^D`.
- Hierarquia: `α` (melhor), `β` (2º), `δ` (3º).
- Coeficiente `a` decai linearmente de 2 → 0.
- O solver é **agnóstico ao problema** (recebe `obj_func`).
"""

# ============================================================
# SEÇÃO 2: GWO canônico (implementado do zero)
# ============================================================
class GWO:
    """
    Grey Wolf Optimizer (Mirjalili et al., 2014).

    Parâmetros
    ----------
    obj_func : callable
        Função objetivo a MINIMIZAR: f(x) -> float
    dim : int
        Dimensionalidade do espaço de busca.
    lb, ub : array-like
        Limites inferior e superior de cada dimensão.
    n_wolves : int
        Tamanho da população.
    max_iter : int
        Número máximo de iterações.
    seed : int or None
        Semente para reprodutibilidade.
    a_decay : {"linear", "exponential", "sqrt"}
        Estratégia de decaimento do coeficiente `a` (2 → 0).
        - "linear"      : a = 2 - 2·(t/T)          (canônico, Mirjalili 2014)
        - "exponential" : a = 2·(1 - (t/T)²)       (decaimento mais rápido)
        - "sqrt"        : a = 2·sqrt(1 - t/T)      (decaimento mais lento)
    """

    def __init__(self, obj_func, dim, lb, ub, n_wolves=30, max_iter=500,
                 seed=None, a_decay="linear"):
        self.obj_func = obj_func
        self.dim = dim
        self.lb = np.full(dim, lb) if np.isscalar(lb) else np.asarray(lb, dtype=float)
        self.ub = np.full(dim, ub) if np.isscalar(ub) else np.asarray(ub, dtype=float)
        self.n_wolves = n_wolves
        self.max_iter = max_iter
        self.seed = seed
        self.a_decay = a_decay
        if a_decay not in ("linear", "exponential", "sqrt"):
            raise ValueError(f"a_decay inválido: {a_decay!r}")
        self.history = []       # melhor fitness por iteração
        self.n_evals = 0

    def _eval(self, x):
        self.n_evals += 1
        return self.obj_func(x)

    def _compute_a(self, t):
        """Coeficiente `a` que decai de 2 → 0 conforme a estratégia escolhida."""
        progress = t / self.max_iter
        if self.a_decay == "linear":
            return 2.0 - 2.0 * progress
        elif self.a_decay == "exponential":
            return 2.0 * (1.0 - progress ** 2)
        else:  # "sqrt"
            return 2.0 * np.sqrt(max(0.0, 1.0 - progress))

    def optimize(self):
        rng = np.random.default_rng(self.seed)

        # 1) Inicialização
        positions = rng.uniform(self.lb, self.ub, size=(self.n_wolves, self.dim))
        fitness = np.array([self._eval(p) for p in positions])

        # 2) Identifica α, β, δ
        order = np.argsort(fitness)
        alpha_pos, alpha_score = positions[order[0]].copy(), fitness[order[0]]
        beta_pos,  beta_score  = positions[order[1]].copy(), fitness[order[1]]
        delta_pos, delta_score = positions[order[2]].copy(), fitness[order[2]]

        self.history = [alpha_score]

        # 3) Loop principal
        for t in range(self.max_iter):
            a = self._compute_a(t)

            for i in range(self.n_wolves):
                for d in range(self.dim):
                    # --- em direção a α ---
                    r1, r2 = rng.random(), rng.random()
                    A1 = 2 * a * r1 - a
                    C1 = 2 * r2
                    D_alpha = abs(C1 * alpha_pos[d] - positions[i, d])
                    X1 = alpha_pos[d] - A1 * D_alpha

                    # --- em direção a β ---
                    r1, r2 = rng.random(), rng.random()
                    A2 = 2 * a * r1 - a
                    C2 = 2 * r2
                    D_beta = abs(C2 * beta_pos[d] - positions[i, d])
                    X2 = beta_pos[d] - A2 * D_beta

                    # --- em direção a δ ---
                    r1, r2 = rng.random(), rng.random()
                    A3 = 2 * a * r1 - a
                    C3 = 2 * r2
                    D_delta = abs(C3 * delta_pos[d] - positions[i, d])
                    X3 = delta_pos[d] - A3 * D_delta

                    positions[i, d] = (X1 + X2 + X3) / 3.0

                # Respeita os limites
                positions[i] = np.clip(positions[i], self.lb, self.ub)

                # Avalia nova posição
                fit = self._eval(positions[i])
                fitness[i] = fit

                # Atualiza hierarquia
                if fit < alpha_score:
                    delta_pos, delta_score = beta_pos.copy(), beta_score
                    beta_pos,  beta_score  = alpha_pos.copy(), alpha_score
                    alpha_pos, alpha_score = positions[i].copy(), fit
                elif fit < beta_score:
                    delta_pos, delta_score = beta_pos.copy(), beta_score
                    beta_pos,  beta_score  = positions[i].copy(), fit
                elif fit < delta_score:
                    delta_pos, delta_score = positions[i].copy(), fit

            self.history.append(alpha_score)

        return alpha_pos, alpha_score, np.array(self.history)

"""## 3. Funções de Benchmark

Para validar a corretude da implementação, usamos três funções clássicas
de teste em otimização contínua. Todas têm **mínimo global conhecido = 0**.

| Função     | Domínio       | Mínimo |
|------------|---------------|--------|
| Rastrigin  | [-5.12, 5.12] | 0      |
| Rosenbrock | [-30, 30]     | 0      |
| Ackley     | [-32, 32]     | 0      |
"""

def rastrigin(x):
    A = 10
    return A * len(x) + np.sum(x**2 - A * np.cos(2 * np.pi * x))

def rosenbrock(x):
    return np.sum(100.0 * (x[1:] - x[:-1]**2)**2 + (1 - x[:-1])**2)

def ackley(x):
    n = len(x)
    s1 = np.sum(x**2)
    s2 = np.sum(np.cos(2 * np.pi * x))
    return -20 * np.exp(-0.2 * np.sqrt(s1 / n)) - np.exp(s2 / n) + 20 + np.e

